// Translate one key. Falls back to English when a key is missing.
function dblT(lang, key) {
  const table = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const value = table[key];
  if (value !== undefined) return value;
  return TRANSLATIONS.en[key] !== undefined ? TRANSLATIONS.en[key] : key;
}

// Arabic is written right to left.
function dblDir(lang) {
  return lang === "ar" ? "rtl" : "ltr";
}

// Apply a language to every [data-i18n] / [data-i18n-placeholder] element
// inside rootElement, and set lang + dir on that root.
function dblApply(rootElement, lang) {
  rootElement.setAttribute("lang", lang);
  rootElement.setAttribute("dir", dblDir(lang));
  rootElement.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = dblT(lang, el.getAttribute("data-i18n"));
  });
  rootElement.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", dblT(lang, el.getAttribute("data-i18n-placeholder")));
  });
  // Language buttons show which language is active.
  rootElement.querySelectorAll(".language__button").forEach((button) => {
    const active = button.getAttribute("data-lang") === lang;
    button.classList.toggle("ist-aktiv", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });
}

